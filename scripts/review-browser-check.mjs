// Only for review-preview.ts + local Vite proxy. Does not access production.
import { createRequire } from 'node:module'
import path from 'node:path'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const require = createRequire(path.resolve('.studyhub-local/browser-test/package.json'))
const { chromium } = require('playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const context = await browser.newContext({ viewport: { width: 1360, height: 960 } })
await context.route('**/*', route => {
  const url = new URL(route.request().url())
  return url.hostname === '127.0.0.1' || ['data:', 'blob:'].includes(url.protocol) ? route.continue() : route.abort()
})
const page = await context.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const rail = page.getByRole('complementary', { name: 'Панель проверки' })
const until = async (fn, label) => { for (let i = 0; i < 100; i++) { if (await fn()) return; await new Promise(r => setTimeout(r, 150)) } throw new Error('Timeout: ' + label) }
const launch = async name => { await Promise.all([page.waitForNavigation({ waitUntil: 'domcontentloaded' }), rail.getByRole('button', { name: 'Запустить: ' + name, exact: true }).click()]) }
try {
  assert.equal((await fetch('http://127.0.0.1:4319/__test/reset', { method: 'POST' })).status, 200)
  await page.goto('http://127.0.0.1:4320/__test/login')
  await page.getByRole('heading', { name: 'Кабинет проверки Study Hub' }).waitFor()
  const ownerToken = await page.evaluate(() => localStorage.getItem('studyhub-token'))
  await page.getByRole('button', { name: 'Начать проверку · 8 шагов' }).click()
  await launch('Тестовый ученик A')
  await page.getByRole('heading', { name: 'Мой английский со Skylla' }).waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('studyhub-token')), ownerToken)
  assert.notEqual(await page.evaluate(() => sessionStorage.getItem('studyhub-token')), ownerToken)
  await rail.getByLabel('Шаг проверки').selectOption('3')
  await page.getByLabel('Моя работа', { exact: true }).fill('Synthetic private learner A draft for the owner review test.')
  await until(async () => page.getByText(/Черновик сохранён в аккаунте/).isVisible(), 'student A draft')
  await rail.getByLabel('Моё замечание').fill('Synthetic feedback: clarify the draft saved message.')
  await page.reload()
  await rail.getByLabel('Шаг проверки').waitFor()
  assert.equal(await rail.getByLabel('Шаг проверки').inputValue(), '3', 'step survives reload')
  assert.match(await rail.getByLabel('Моё замечание').inputValue(), /Synthetic feedback/)
  assert.match(await page.getByLabel('Моя работа', { exact: true }).inputValue(), /learner A draft/)
  await rail.getByRole('button', { name: 'Не работает', exact: true }).click()
  await rail.getByText('Результат шага сохранён.').waitFor()
  await rail.getByRole('button', { name: 'Отправить замечание в очередь' }).click()
  await rail.getByText('Замечание сохранено в приватной очереди.').waitFor()
  await rail.getByLabel('Шаг проверки').selectOption('6')
  await launch('Тестовый ученик B')
  await page.getByLabel('Моя работа', { exact: true }).waitFor()
  await until(async () => (await rail.getByLabel('Шаг проверки').inputValue()) === '6', 'step survives role switch')
  assert.equal(await page.getByLabel('Моя работа', { exact: true }).inputValue(), '', 'student B cannot see A draft')
  await rail.getByLabel('Шаг проверки').selectOption('7')
  await launch('Тестовый ученик A')
  await page.getByLabel('Моя работа', { exact: true }).waitFor()
  await until(async () => (await page.getByLabel('Моя работа', { exact: true }).inputValue()).includes('learner A draft'), 'A draft restored')
  await page.screenshot({ path: '.studyhub-local/review-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile page width')
  await page.screenshot({ path: '.studyhub-local/review-mobile.png', fullPage: true })
  await rail.getByRole('button', { name: 'Свернуть панель проверки' }).click()
  await page.getByRole('button', { name: 'Тестовая роль · Проверка' }).click()
  await rail.getByRole('button', { name: 'Завершить и вернуться владельцем' }).click()
  await page.getByRole('heading', { name: 'Кабинет проверки Study Hub' }).waitFor()
  await rail.getByRole('button', { name: 'Убрать панель, сохранив проверку' }).click()
  assert.equal(await page.evaluate(() => localStorage.getItem('studyhub-token')), ownerToken)
  assert.equal(await page.evaluate(() => sessionStorage.getItem('studyhub-token')), null)
  await page.getByText('Synthetic feedback: clarify the draft saved message.', { exact: true }).first().waitFor()
  await page.getByText('Обработка замечания').click()
  await page.getByLabel('Что сделано или нужно уточнить').fill('Synthetic triage note')
  await page.getByRole('button', { name: 'В работу', exact: true }).click()
  await page.getByText(/in-progress: Synthetic triage note/).waitFor()
  await page.reload()
  await page.getByText('Synthetic feedback: clarify the draft saved message.', { exact: true }).first().waitFor()
  await page.getByRole('button', { name: 'Создать ключ чтения' }).click()
  const key = await page.getByLabel('Ключ чтения очереди').inputValue()
  const feed = await fetch('http://127.0.0.1:4319/api/review-feed', { headers: { Authorization: 'Bearer ' + key } })
  assert.equal(feed.status, 200)
  const report = await feed.json()
  assert.equal(report.feedback.length, 1)
  assert.equal(report.feedback[0].data.status, 'in-progress')
  assert.ok(!JSON.stringify(report).includes(key), 'key excluded from report')
  await page.getByRole('button', { name: 'Отозвать ключ' }).click()
  await page.getByText('Ключ чтения отозван.').waitFor()
  assert.equal((await fetch('http://127.0.0.1:4319/api/review-feed', { headers: { Authorization: 'Bearer ' + key } })).status, 401)
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать отчёт' }).click()
  const download = await downloadPromise
  await download.saveAs('.studyhub-local/review-browser-export.json')
  assert.equal(JSON.parse(await fs.readFile('.studyhub-local/review-browser-export.json', 'utf8')).feedback.length, 1)
  await page.setViewportSize({ width: 1360, height: 960 })
  await page.screenshot({ path: '.studyhub-local/review-owner.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: real UI and HTTP routes; scenario, step/comment reload, bounded role switching, A/B draft isolation, owner return, persistent feedback, triage, reader feed/revoke/export, mobile panel. Synthetic database and AI only.')
} catch (e) {
  await page.screenshot({ path: '.studyhub-local/review-browser-failure.png', fullPage: true })
  console.error((await page.locator('body').innerText()).slice(0, 6000)); throw e
} finally { await browser.close() }
