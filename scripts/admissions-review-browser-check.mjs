async function ownerCall(method, endpoint, body) {
  return page.evaluate(async ({method,endpoint,body}) => {
    const response=await fetch('/api/review'+endpoint,{method,headers:{Authorization:'Bearer '+localStorage.getItem('studyhub-token'),'Content-Type':'application/json','X-StudyHub-Build':'aaaaaaaa'},body:body===undefined?undefined:JSON.stringify(body)})
    if(!response.ok) throw new Error('Owner request: '+response.status)
    return response.json()
  },{method,endpoint,body})
}
